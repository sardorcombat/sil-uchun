(function () {
  function getLang() {
    var s = localStorage.getItem('sil_lang');
    return (s && DICT[s]) ? s : 'uz';
  }
  function apply(lang) {
    if (!DICT[lang]) lang = 'uz';
    var d = DICT[lang];
    localStorage.setItem('sil_lang', lang);
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      if (d[k] != null) el.textContent = d[k];
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var k = el.getAttribute('data-i18n-html');
      if (d[k] != null) el.innerHTML = d[k];
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      var k = el.getAttribute('data-i18n-ph');
      if (d[k] != null) el.setAttribute('placeholder', d[k]);
    });
    document.querySelectorAll('.lang a').forEach(function (a) {
      a.classList.toggle('active', a.getAttribute('data-lang') === lang);
    });
  }

  // Boshqa skriptlar (main.js) joriy tarjimani olishi uchun
  window.silLang = getLang;
  window.silT = function (key) {
    var d = DICT[getLang()] || DICT.uz;
    return d[key] != null ? d[key] : (DICT.uz[key] != null ? DICT.uz[key] : key);
  };

  document.addEventListener('DOMContentLoaded', function () {
    document.querySelectorAll('.lang a').forEach(function (a) {
      a.addEventListener('click', function (e) {
        e.preventDefault();
        apply(a.getAttribute('data-lang'));
      });
    });
    apply(getLang());
  });
})();
